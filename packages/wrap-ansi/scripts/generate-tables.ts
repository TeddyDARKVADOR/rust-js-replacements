/**
 * Generates `rust/core/src/tables.rs`.
 *
 * The tables come from the same sources wrap-ansi 10.0.2 uses at runtime:
 *
 * - `Spacing_Mark`, used by the width rules of string-width 8.3.0, comes from the V8 regular
 *   expression engine of the running Node.js process.
 * - The SGR open and close codes come from the pinned `ansi-styles` 6.2.3 package.
 *
 * The other Unicode properties are shared with string-width (`string_width_core::unicode`).
 *
 * Usage: node scripts/generate-tables.ts
 */

import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import ansiStyles from 'ansi-styles';

type Range = [start: number, end: number];

const MAX_CODE_POINT = 0x10ffff;
const OUTPUT_PATH = join(dirname(fileURLToPath(import.meta.url)), '../rust/core/src/tables.rs');

function isSurrogate(codePoint: number): boolean {
  return codePoint >= 0xd800 && codePoint <= 0xdfff;
}

/** Collects the ranges of scalar values (surrogates excluded) that have the property. */
function propertyRanges(property: string): Range[] {
  const regex = new RegExp(`^\\p{${property}}$`, 'v');
  const ranges: Range[] = [];
  let start = -1;

  for (let codePoint = 0; codePoint <= MAX_CODE_POINT + 1; codePoint++) {
    const matches =
      codePoint <= MAX_CODE_POINT &&
      !isSurrogate(codePoint) &&
      regex.test(String.fromCodePoint(codePoint));

    if (matches && start === -1) {
      start = codePoint;
    } else if (!matches && start !== -1) {
      ranges.push([start, codePoint - 1]);
      start = -1;
    }
  }

  return ranges;
}

function hex(value: number): string {
  const digits = value.toString(16).toUpperCase().padStart(4, '0');
  // Group digits by four from the right, as required by clippy::unreadable_literal.
  return `0x${digits.length > 4 ? `${digits.slice(0, -4).padStart(4, '0')}_${digits.slice(-4)}` : digits}`;
}

function formatRanges(name: string, documentation: string, ranges: Range[]): string {
  const rows = ranges.map(([start, end]) => `    (${hex(start)}, ${hex(end)}),`).join('\n');
  return `/// ${documentation}\npub(crate) static ${name}: &[(u32, u32)] = &[\n${rows}\n];\n`;
}

function formatStyleCodes(): string {
  const rows = [...ansiStyles.codes]
    .sort(([left], [right]) => left - right)
    .map(([open, close]) => `    (${open}, ${close}),`)
    .join('\n');
  return `/// SGR codes that open a style, with the code that closes it (\`ansiStyles.codes\`), sorted.\npub(crate) static STYLE_CLOSE_CODES: &[(u32, u32)] = &[\n${rows}\n];\n`;
}

function main(): void {
  const unicodeVersion = process.versions.unicode;
  if (!unicodeVersion) {
    throw new Error('process.versions.unicode is not available');
  }

  const sections = [
    '// @generated by packages/wrap-ansi/scripts/generate-tables.ts. Do not edit by hand.',
    `// Node.js ${process.version}, V8 ${process.versions.v8}, ICU ${process.versions.icu}, Unicode ${unicodeVersion}, ansi-styles 6.2.3.`,
    '',
    formatRanges(
      'SPACING_MARK',
      '`Spacing_Mark` (`General_Category` Mc).',
      propertyRanges('Spacing_Mark'),
    ),
    formatStyleCodes(),
  ];

  writeFileSync(OUTPUT_PATH, sections.join('\n'));
  execFileSync('cargo', ['fmt', '--package', 'wrap-ansi-core'], { stdio: 'inherit' });
  console.log(`Wrote ${OUTPUT_PATH}.`);
}

main();
